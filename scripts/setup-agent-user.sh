#!/usr/bin/env bash
set -euo pipefail

# setup-agent-user.sh — Provision the agent-process-isolation substrate.
#
# Creates the unprivileged `agentworker` Unix user that agent subprocesses run
# as, hardens the daemon's root dir and token files, builds the per-session
# clone + agent-socket directory layout, installs the fixed root-owned wrapper
# scripts, and locks down `agentworker` egress through a hostname-filtering
# tinyproxy + iptables.
#
# Idempotent: safe to re-run. Must run as root.
#
# Usage:
#   sudo KIRO_PATH=/abs/path/to/kiro ROOTDIR=/home/agentrouter/.agent-router \
#        ./scripts/setup-agent-user.sh
#
# Environment:
#   KIRO_PATH   Absolute path to the kiro executable (required). Taken from
#               config.json "kiroPath". MUST NOT live under $ROOTDIR.
#   ROOTDIR     The daemon's root directory (default: /home/agentrouter/.agent-router).
#   WORKTREE_BASE  Per-session clone base (default: /srv/agent-router/worktrees).
#   PUSH_TMP_BASE  Daemon-owned push staging base (default: /srv/agent-router/push-tmp).
#
# See docs/security-setup.md and .kiro/specs/agent-process-isolation/ for the
# full threat model and verification steps.

WORKER_USER="agentworker"
WORKER_HOME="/home/${WORKER_USER}"
DAEMON_USER="agentrouter"

ROOTDIR="${ROOTDIR:-/home/${DAEMON_USER}/.agent-router}"
WORKTREE_BASE="${WORKTREE_BASE:-/srv/agent-router/worktrees}"
PUSH_TMP_BASE="${PUSH_TMP_BASE:-/srv/agent-router/push-tmp}"
KIRO_PATH="${KIRO_PATH:-}"

SUDOERS_FILE="/etc/sudoers.d/agent-router-worker"
SEED_CLONE_WRAPPER="/usr/local/libexec/agent-router-seed-clone"
RM_SESSION_WRAPPER="/usr/local/libexec/agent-router-rm-session"
ASKPASS_HELPER="/usr/local/libexec/agent-router-askpass"
TMPFILES_CONF="/etc/tmpfiles.d/agent-router.conf"
TINYPROXY_CONF="/etc/tinyproxy/tinyproxy.conf"
TINYPROXY_FILTER="/etc/tinyproxy/filter"
IPTABLES_DIR="/etc/iptables"
IPTABLES_V4="${IPTABLES_DIR}/agent-router-rules.v4"
IPTABLES_V6="${IPTABLES_DIR}/agent-router-rules.v6"
IPTABLES_UNIT="/etc/systemd/system/agent-router-iptables.service"

info()  { printf '\033[1;34m[info]\033[0m  %s\n' "$1"; }
warn()  { printf '\033[1;33m[warn]\033[0m  %s\n' "$1"; }
error() { printf '\033[1;31m[error]\033[0m %s\n' "$1" >&2; }

# ---------- Preconditions ----------

require_root() {
  if [ "$(id -u)" -ne 0 ]; then
    error "This script must run as root (use sudo)."
    exit 1
  fi
}

validate_kiro_path() {
  if [ -z "$KIRO_PATH" ]; then
    error "KIRO_PATH is required. Set it to the absolute kiroPath from config.json."
    exit 1
  fi
  case "$KIRO_PATH" in
    /*) ;;
    *) error "KIRO_PATH must be an absolute path: $KIRO_PATH"; exit 1 ;;
  esac
  # The kiro binary must NOT live under $ROOTDIR — otherwise agentworker (which
  # cannot read $ROOTDIR) could not exec it, and worse, a writable path under a
  # daemon dir would widen the sudo rule's attack surface.
  local real_root real_kiro
  real_root="$(readlink -f "$ROOTDIR" 2>/dev/null || echo "$ROOTDIR")"
  real_kiro="$(readlink -f "$KIRO_PATH" 2>/dev/null || echo "$KIRO_PATH")"
  case "$real_kiro" in
    "$real_root"/*)
      error "KIRO_PATH ($real_kiro) must NOT live under ROOTDIR ($real_root)."
      exit 1
      ;;
  esac
}

# ---------- 1. Create agentworker user ----------

create_worker_user() {
  if id -u "$WORKER_USER" &>/dev/null; then
    info "User '$WORKER_USER' already exists."
  else
    info "Creating system user '$WORKER_USER' with home '$WORKER_HOME'..."
    useradd -r -s /usr/sbin/nologin -d "$WORKER_HOME" -m "$WORKER_USER"
  fi
}

# ---------- 2. + 7. Sudoers rule ----------

write_sudoers() {
  info "Writing sudoers rule to $SUDOERS_FILE..."
  local tmp
  tmp="$(mktemp)"
  cat > "$tmp" << EOF
# Generated by scripts/setup-agent-user.sh — DO NOT EDIT
Defaults:${DAEMON_USER} env_keep += "AGENT_ROUTER_SESSION_ID WORKDIR AGENT_ROUTER_AGENT_SOCK AGENT_ROUTER_CAP_TOKEN HTTPS_PROXY"
${DAEMON_USER} ALL=(${WORKER_USER}) NOPASSWD: ${KIRO_PATH} acp
# Wrapper scripts — BASE hardcoded in scripts, only SID arg is variable
${DAEMON_USER} ALL=(root) NOPASSWD: ${SEED_CLONE_WRAPPER} *
${DAEMON_USER} ALL=(root) NOPASSWD: ${RM_SESSION_WRAPPER} *
# Reap stray agentworker processes after the LAST worker session ends (guarded
# in the daemon by getActiveWorkerSessionCount() — never with siblings active).
${DAEMON_USER} ALL=(root) NOPASSWD: /usr/bin/pkill -KILL -u ${WORKER_USER}
# Read-only git inspection of agentworker work/ for the daemon. Output is
# treated as untrusted (the agent controls that tree's .git/config).
${DAEMON_USER} ALL=(${WORKER_USER}) NOPASSWD: /usr/bin/git -C ${WORKTREE_BASE}/* rev-parse HEAD
${DAEMON_USER} ALL=(${WORKER_USER}) NOPASSWD: /usr/bin/git -C ${WORKTREE_BASE}/* log --format\=* -n *
EOF
  # Validate before installing — a bad sudoers file can lock out sudo entirely.
  if ! visudo -c -f "$tmp" >/dev/null; then
    error "Generated sudoers file failed validation. Not installing."
    rm -f "$tmp"
    exit 1
  fi
  install -o root -g root -m 440 "$tmp" "$SUDOERS_FILE"
  rm -f "$tmp"
  info "Sudoers rule installed and validated."
}

# ---------- 3. Harden rootDir + token files ----------

harden_rootdir() {
  if [ ! -d "$ROOTDIR" ]; then
    warn "ROOTDIR '$ROOTDIR' does not exist yet — creating it (daemon-owned)."
    install -d -o "$DAEMON_USER" -g "$DAEMON_USER" -m 750 "$ROOTDIR"
  else
    info "Hardening $ROOTDIR (chmod 750, owner ${DAEMON_USER})..."
    chown "${DAEMON_USER}:${DAEMON_USER}" "$ROOTDIR"
    chmod 750 "$ROOTDIR"
  fi
  local f
  for f in tokens.json daemon-token config.json; do
    if [ -e "${ROOTDIR}/${f}" ]; then
      info "Hardening ${ROOTDIR}/${f} (chmod 600)..."
      chown "${DAEMON_USER}:${DAEMON_USER}" "${ROOTDIR}/${f}"
      chmod 600 "${ROOTDIR}/${f}"
    fi
  done
}

# ---------- 4. Per-session clone + push-tmp base dirs ----------

create_base_dirs() {
  # setgid 2755 so new {sid}/ dirs inherit the agentworker group; seed.bundle
  # (mode 0640) is then readable by agentworker without an explicit chgrp.
  info "Creating $WORKTREE_BASE (2755 ${DAEMON_USER}:${WORKER_USER})..."
  install -d -o "$DAEMON_USER" -g "$WORKER_USER" -m 2755 "$WORKTREE_BASE"
  # push-tmp is daemon-only (0700) — the agent never touches it.
  info "Creating $PUSH_TMP_BASE (0700 ${DAEMON_USER})..."
  install -d -o "$DAEMON_USER" -g "$DAEMON_USER" -m 700 "$PUSH_TMP_BASE"
}

# ---------- 5. Agent socket dir via tmpfiles.d ----------

create_socket_dir() {
  info "Writing tmpfiles.d entry for /run/agent-router..."
  echo "d /run/agent-router 2750 ${DAEMON_USER} ${WORKER_USER} -" > "$TMPFILES_CONF"
  # Apply immediately so the dir exists this boot without a reboot.
  systemd-tmpfiles --create "$TMPFILES_CONF" 2>/dev/null || {
    warn "systemd-tmpfiles not available — creating /run/agent-router directly."
    install -d -o "$DAEMON_USER" -g "$WORKER_USER" -m 2750 /run/agent-router
  }
}

# ---------- 6. Fixed root-owned wrapper scripts + askpass helper ----------

install_wrappers() {
  info "Installing wrapper scripts under /usr/local/libexec..."
  install -d -o root -g root -m 755 /usr/local/libexec

  local tmp
  tmp="$(mktemp)"
  cat > "$tmp" << EOF
#!/bin/bash
# Generated by scripts/setup-agent-user.sh — DO NOT EDIT
# Usage: agent-router-seed-clone <sessionId>
# BASE is hardcoded to prevent path traversal. SID validated against strict regex.
set -euo pipefail
BASE="${WORKTREE_BASE}"
SID="\$1"
if ! [[ "\$SID" =~ ^[A-Za-z0-9-]{1,64}\$ ]]; then
  echo "Invalid session ID" >&2; exit 1
fi
WORK="\$BASE/\$SID/work"
BUNDLE="\$BASE/\$SID/seed.bundle"
# Create work/ as agentworker (not root) so agentworker can write into it.
install -d -o ${WORKER_USER} -g ${WORKER_USER} -m 0755 "\$WORK"
sudo -u ${WORKER_USER} /usr/bin/git clone "\$BUNDLE" "\$WORK" \\
  --config safe.directory="\$WORK" --config core.hooksPath=/dev/null
EOF
  install -o root -g root -m 755 "$tmp" "$SEED_CLONE_WRAPPER"
  rm -f "$tmp"

  tmp="$(mktemp)"
  cat > "$tmp" << EOF
#!/bin/bash
# Generated by scripts/setup-agent-user.sh — DO NOT EDIT
# Usage: agent-router-rm-session <sessionId>
# BASE is hardcoded. SID validated. work/ removed as agentworker to avoid permission issues.
set -euo pipefail
BASE="${WORKTREE_BASE}"
SID="\$1"
if ! [[ "\$SID" =~ ^[A-Za-z0-9-]{1,64}\$ ]]; then
  echo "Invalid session ID" >&2; exit 1
fi
SESSION_DIR="\$BASE/\$SID"
# Remove agentworker-owned work/ as agentworker.
sudo -u ${WORKER_USER} /bin/rm -rf "\$SESSION_DIR/work" 2>/dev/null || true
# Remove the session dir itself (daemon-owned).
rm -rf "\$SESSION_DIR"
EOF
  install -o root -g root -m 755 "$tmp" "$RM_SESSION_WRAPPER"
  rm -f "$tmp"

  tmp="$(mktemp)"
  cat > "$tmp" << 'EOF'
#!/bin/sh
# Generated by scripts/setup-agent-user.sh — DO NOT EDIT
# Answers git credential prompts for daemon-side git push. The PAT is passed to
# the git child process via GIT_ASKPASS_PASSWORD — never written to disk or argv.
echo "${GIT_ASKPASS_PASSWORD}"
EOF
  install -o root -g root -m 755 "$tmp" "$ASKPASS_HELPER"
  rm -f "$tmp"

  info "Wrapper scripts installed."
}

# ---------- 8. tinyproxy ----------

install_tinyproxy() {
  if ! command -v tinyproxy &>/dev/null; then
    if command -v apt-get &>/dev/null; then
      info "Installing tinyproxy via apt..."
      apt-get update -qq
      apt-get install -y -qq tinyproxy
    else
      error "tinyproxy not found and apt-get unavailable. Install tinyproxy manually."
      exit 1
    fi
  else
    info "tinyproxy already installed."
  fi

  # FilterType directive differs across tinyproxy versions.
  local tp_ver tp_major tp_minor filter_type
  tp_ver="$(tinyproxy -v 2>&1 | grep -oE '[0-9]+\.[0-9]+' | head -1 || echo '1.10')"
  tp_major="$(echo "$tp_ver" | cut -d. -f1)"
  tp_minor="$(echo "$tp_ver" | cut -d. -f2)"
  if [ "$tp_major" -gt 1 ] || { [ "$tp_major" -eq 1 ] && [ "$tp_minor" -ge 11 ]; }; then
    filter_type="FilterType ere"
  else
    filter_type="FilterExtended Yes"
  fi

  info "Writing $TINYPROXY_CONF (version $tp_ver → $filter_type)..."
  cat > "$TINYPROXY_CONF" << EOF
Port 8080
Listen 127.0.0.1
Allow 127.0.0.0/8
ConnectPort 443
User tinyproxy
Group tinyproxy
Filter "${TINYPROXY_FILTER}"
FilterDefaultDeny Yes
${filter_type}
EOF

  info "Writing $TINYPROXY_FILTER (anchored ERE allowlist)..."
  cat > "$TINYPROXY_FILTER" << 'EOF'
^(.+\.)?api\.github\.com$
^(.+\.)?github\.com$
^objects\.githubusercontent\.com$
^api\.anthropic\.com$
^(.+\.)?amazonaws\.com$
^(.+\.)?kiro\.dev$
^registry\.npmjs\.org$
EOF

  systemctl enable --now tinyproxy
  info "tinyproxy enabled and started."
}

# tinyproxy SSRF prevention: block the tinyproxy uid from reaching link-local
# and RFC1918 ranges (and IPv6 cloud-metadata ranges) so a filtered hostname
# that resolves to a private IP cannot be used to pivot internally.
# Builds a dedicated TPROXY_SSRF_BLOCK chain only — the jump + persist happen
# in setup_iptables(). Called BEFORE the save step there.
setup_tinyproxy_ssrf_rules() {
  info "Building TPROXY_SSRF_BLOCK chain (SSRF guard for tinyproxy uid)..."
  iptables -L TPROXY_SSRF_BLOCK -n &>/dev/null || iptables -N TPROXY_SSRF_BLOCK
  iptables -F TPROXY_SSRF_BLOCK
  local tmp
  tmp="$(mktemp)"
  cat > "$tmp" << 'RULES'
*filter
:TPROXY_SSRF_BLOCK - [0:0]
-A TPROXY_SSRF_BLOCK -d 169.254.0.0/16 -j REJECT
-A TPROXY_SSRF_BLOCK -d 10.0.0.0/8 -j REJECT
-A TPROXY_SSRF_BLOCK -d 172.16.0.0/12 -j REJECT
-A TPROXY_SSRF_BLOCK -d 192.168.0.0/16 -j REJECT
-A TPROXY_SSRF_BLOCK -j RETURN
COMMIT
RULES
  iptables-restore --noflush "$tmp"
  rm -f "$tmp"

  # IPv6 counterpart: block unique-local + cloud metadata (fd00::/8 covers
  # ULA; link-local fe80::/10; drop any to be safe before RETURN).
  ip6tables -L TPROXY_SSRF_BLOCK -n &>/dev/null || ip6tables -N TPROXY_SSRF_BLOCK
  ip6tables -F TPROXY_SSRF_BLOCK
  local tmp6
  tmp6="$(mktemp)"
  cat > "$tmp6" << 'RULES6'
*filter
:TPROXY_SSRF_BLOCK - [0:0]
-A TPROXY_SSRF_BLOCK -d fd00::/8 -j REJECT
-A TPROXY_SSRF_BLOCK -d fe80::/10 -j REJECT
-A TPROXY_SSRF_BLOCK -j RETURN
COMMIT
RULES6
  ip6tables-restore --noflush "$tmp6"
  rm -f "$tmp6"
}

# ---------- 9. iptables rules (atomic, no policy lines) ----------

setup_iptables() {
  info "Installing iptables egress rules for '$WORKER_USER'..."

  # IPv4: dedicated chain, built in a tempfile with ONLY the chain (no built-in
  # policy lines), applied with --noflush so Docker/ufw rules are untouched.
  iptables -L AGENTWORKER_OUT -n &>/dev/null || iptables -N AGENTWORKER_OUT
  iptables -F AGENTWORKER_OUT
  local tmp
  tmp="$(mktemp)"
  cat > "$tmp" << 'RULES'
*filter
:AGENTWORKER_OUT - [0:0]
-A AGENTWORKER_OUT -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT
-A AGENTWORKER_OUT -d 127.0.0.1 -p tcp --dport 8080 -j ACCEPT
-A AGENTWORKER_OUT -j REJECT --reject-with icmp-port-unreachable
COMMIT
RULES
  iptables-restore --noflush "$tmp"
  rm -f "$tmp"
  iptables -C OUTPUT -m owner --uid-owner "$WORKER_USER" -j AGENTWORKER_OUT 2>/dev/null || \
    iptables -I OUTPUT 1 -m owner --uid-owner "$WORKER_USER" -j AGENTWORKER_OUT

  # IPv6: default DROP from AGENTWORKER_OUT — no direct IPv6 egress at all.
  ip6tables -L AGENTWORKER_OUT -n &>/dev/null || ip6tables -N AGENTWORKER_OUT
  ip6tables -F AGENTWORKER_OUT
  local tmp6
  tmp6="$(mktemp)"
  printf '*filter\n:AGENTWORKER_OUT - [0:0]\n-A AGENTWORKER_OUT -j DROP\nCOMMIT\n' > "$tmp6"
  ip6tables-restore --noflush "$tmp6"
  rm -f "$tmp6"
  ip6tables -C OUTPUT -m owner --uid-owner "$WORKER_USER" -j AGENTWORKER_OUT 2>/dev/null || \
    ip6tables -I OUTPUT 1 -m owner --uid-owner "$WORKER_USER" -j AGENTWORKER_OUT

  # Build the tinyproxy SSRF chain BEFORE persisting so both chains are saved.
  setup_tinyproxy_ssrf_rules

  # Persist as VALID standalone restore files (header + both chains + COMMIT).
  mkdir -p "$IPTABLES_DIR"
  local tproxy_uid
  tproxy_uid="$(id -u tinyproxy)"
  {
    echo '*filter'
    echo ':AGENTWORKER_OUT - [0:0]'
    echo ':TPROXY_SSRF_BLOCK - [0:0]'
    iptables -S AGENTWORKER_OUT | tail -n +2
    iptables -S TPROXY_SSRF_BLOCK | tail -n +2
    echo "-I OUTPUT 1 -m owner --uid-owner ${WORKER_USER} -j AGENTWORKER_OUT"
    echo "-I OUTPUT 2 -m owner --uid-owner ${tproxy_uid} -j TPROXY_SSRF_BLOCK"
    echo 'COMMIT'
  } > "$IPTABLES_V4"
  {
    echo '*filter'
    echo ':AGENTWORKER_OUT - [0:0]'
    echo ':TPROXY_SSRF_BLOCK - [0:0]'
    ip6tables -S AGENTWORKER_OUT | tail -n +2
    ip6tables -S TPROXY_SSRF_BLOCK | tail -n +2
    echo "-I OUTPUT 1 -m owner --uid-owner ${WORKER_USER} -j AGENTWORKER_OUT"
    echo "-I OUTPUT 2 -m owner --uid-owner ${tproxy_uid} -j TPROXY_SSRF_BLOCK"
    echo 'COMMIT'
  } > "$IPTABLES_V6"
  info "Persisted iptables rules to $IPTABLES_V4 and $IPTABLES_V6."

  # Also apply the live jump for the tinyproxy SSRF chain so it is effective now.
  iptables -C OUTPUT -m owner --uid-owner "$tproxy_uid" -j TPROXY_SSRF_BLOCK 2>/dev/null || \
    iptables -I OUTPUT 2 -m owner --uid-owner "$tproxy_uid" -j TPROXY_SSRF_BLOCK
  ip6tables -C OUTPUT -m owner --uid-owner "$tproxy_uid" -j TPROXY_SSRF_BLOCK 2>/dev/null || \
    ip6tables -I OUTPUT 2 -m owner --uid-owner "$tproxy_uid" -j TPROXY_SSRF_BLOCK

  install_iptables_unit
}

install_iptables_unit() {
  info "Installing systemd unit $IPTABLES_UNIT..."
  cat > "$IPTABLES_UNIT" << 'EOF'
[Unit]
Description=Restore agent-router iptables rules
Before=agent-router.service
After=network.target
DefaultDependencies=no

[Service]
Type=oneshot
ExecStart=/sbin/iptables-restore --noflush /etc/iptables/agent-router-rules.v4
ExecStart=/sbin/ip6tables-restore --noflush /etc/iptables/agent-router-rules.v6
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable agent-router-iptables.service
  info "systemd unit enabled (restores both v4 + v6 before agent-router.service)."
}

# ---------- ufw conflict check ----------

check_ufw() {
  if command -v ufw &>/dev/null && ufw status 2>/dev/null | grep -q "Status: active"; then
    error "ufw is active. This setup manages iptables directly and conflicts with ufw."
    error "Either disable ufw ('ufw disable') or add equivalent agentworker egress"
    error "rules via ufw manually. Aborting to avoid breaking your firewall."
    exit 1
  fi
}

# ---------- Main ----------

main() {
  require_root
  validate_kiro_path
  check_ufw

  create_worker_user
  write_sudoers
  harden_rootdir
  create_base_dirs
  create_socket_dir
  install_wrappers
  install_tinyproxy
  setup_iptables

  echo ""
  info "========================================="
  info "Agent process isolation setup complete."
  info "========================================="
  info "Worker user   : $WORKER_USER (home $WORKER_HOME)"
  info "Root dir      : $ROOTDIR (750, token files 600)"
  info "Worktree base : $WORKTREE_BASE (2755)"
  info "Push-tmp base : $PUSH_TMP_BASE (0700)"
  info "Agent socket  : /run/agent-router/agent.sock (dir 2750)"
  info "kiro path     : $KIRO_PATH"
  info ""
  info "Next steps:"
  info "  1. Authenticate kiro for the worker user:"
  info "       sudo -u $WORKER_USER $KIRO_PATH login"
  info "  2. Set \"useWorkerUid\": true in config.json"
  info "  3. Restart the daemon: systemctl restart agent-router"
  info ""
  info "Verify with the AC commands in docs/security-setup.md / README Security Setup."
  info "========================================="
}

main "$@"
